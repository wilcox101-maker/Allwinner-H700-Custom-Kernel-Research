# Generate sun50i-h700-redux-cpu-opp-stock.dtsi from the stock DTS (reference/stock-202505/board.dts).
# Every outcome of the stock speed-bin decoder becomes one Redux opp-supported-hw bit:
#   bit 0 = stock mask 0x1   bit 1 = stock mask 0x2   bit 3 = stock mask 0x8 (stock default)
#   bit 2 = name a1   bit 4 = b0   bit 5 = b1   bit 6 = c0   bit 7 = c1   bit 8 = c2
# Mask outcomes use nodes whose opp-supported-hw has that bit. Name outcomes use the nodes WITHOUT
# opp-supported-hw that carry opp-microvolt-<name>; a node lacking that name is left out (stock had
# no voltage for it). Values are copied as numbers (hardware facts). Python stdlib only.
# Usage: python gen_cpu_opp_stock.py board.dts > sun50i-h700-redux-cpu-opp-stock.dtsi
import re, sys
t = open(sys.argv[1]).read()
s = t[t.index('opp_l_table {'):]
s = s[:s.index('\n    };')]
MASK = {0: 0x1, 1: 0x2, 3: 0x8}
NAME = {2: 'a1', 4: 'b0', 5: 'b1', 6: 'c0', 7: 'c1', 8: 'c2'}
tables = {b: {} for b in list(MASK) + list(NAME)}
for m in re.finditer(r'opp@(\d+)(-[0-9a-z]+)? \{(.*?)\}', s, re.S):
    f = int(m.group(1)); body = m.group(3)
    hw = re.search(r'opp-supported-hw = <(0x[0-9A-Fa-f]+)>', body)
    if hw:
        hw = int(hw.group(1), 16)
        uv = int(re.search(r'opp-microvolt = <(0x[0-9A-Fa-f]+)>', body).group(1), 16)
        for bit, mask in MASK.items():
            if hw & mask:
                assert f not in tables[bit]; tables[bit][f] = uv
    else:
        for bit, name in NAME.items():
            v = re.search(r'opp-microvolt-%s = <(0x[0-9A-Fa-f]+)>' % name, body)
            if v:
                assert f not in tables[bit]; tables[bit][f] = int(v.group(1), 16)
# One node per frequency: opp-supported-hw = every Redux bit that has the step; one
# opp-microvolt if all those bits agree, else opp-microvolt-speed<bit> per bit (the driver sets
# the OPP prop name to "speed<index>"), as the upstream allwinner,sun50i-h6-operating-points schema expects.
freqs = {}
for bit, tab in tables.items():
    for f, uv in tab.items():
        freqs.setdefault(f, {})[bit] = uv
if len(sys.argv) > 2 and sys.argv[2] == '--summary':
    for bit in sorted(tables):
        lab = 'mask 0x%x' % MASK[bit] if bit in MASK else 'name ' + NAME[bit]
        print('bit %d (%s): %s' % (bit, lab, ' '.join('%d@%d' % (f // 10**6, v // 1000) for f, v in sorted(tables[bit].items()))))
    sys.exit()
out = []
w = out.append
w('// SPDX-License-Identifier: (GPL-2.0-only OR BSD-2-Clause)')
w('/*')
w(' * Stock-parity CPU OPPs for the RG34XX-SP. DRAFT, NOT BOOTED. GENERATED by')
w(' * phase2-mainline/tools/gen_cpu_opp_stock.py from reference/stock-202505/board.dts; do not edit.')
w(' * Needs the Redux cpufreq xlate (design doc §2a), compatible "anbernic,rg34xx-sp-operating-points".')
w(' * opp-supported-hw bits (Redux numbering): 0 = stock mask 0x1, 1 = mask 0x2, 3 = mask 0x8 (default),')
w(' * 2 = a1, 4 = b0, 5 = b1, 6 = c0, 7 = c1, 8 = c2. Frequencies/voltages are stock\'s own values.')
w(' */')
w('')
w('/ {')
w('\tredux_cpu_opp_stock: opp-table-reduxstock {')
w('\t\tcompatible = "anbernic,rg34xx-sp-operating-points";')
w('\t\tnvmem-cells = <&cpu_speed_grade>, <&redux_speed_aux_a>, <&redux_speed_aux_b>;')
w('\t\tnvmem-cell-names = "speed", "speed-aux-a", "speed-aux-b";')
w('\t\topp-shared;')
for f in sorted(freqs):
    per = freqs[f]
    bits = sum(1 << b for b in per)
    w('')
    w('\t\topp-%d {' % f)
    w('\t\t\topp-hz = /bits/ 64 <%d>;' % f)
    if len(set(per.values())) == 1:
        w('\t\t\topp-microvolt = <%d>;' % next(iter(per.values())))
    else:
        for b in sorted(per):
            w('\t\t\topp-microvolt-speed%d = <%d>;' % (b, per[b]))
    w('\t\t\tclock-latency-ns = <244144>;')
    w('\t\t\topp-supported-hw = <0x%x>;' % bits)
    w('\t\t};')
w('\t};')
w('};')
w('')
w('&sid {')
w('\t/* SID words +0x220 / +0x228 (value_offset 0x200), read by the stock decoder for fuse 0x5c00. */')
w('\tredux_speed_aux_a: speed-aux-a@20 {')
w('\t\treg = <0x20 0x4>;')
w('\t};')
w('')
w('\tredux_speed_aux_b: speed-aux-b@28 {')
w('\t\treg = <0x28 0x4>;')
w('\t};')
w('};')
for c in range(4):
    w('')
    w('&cpu%d {' % c)
    w('\toperating-points-v2 = <&redux_cpu_opp_stock>;')
    w('};')
print('\n'.join(out))
